"""Generate SYNTHETIC questionnaire responses for demos and tests.

No real survey data is used. Each fictional organisation ("persona") has a
latent 1-5 tendency per dimension; respondents' answers are that tendency plus
noise, rounded onto the item's answer scale.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from lamf.framework import Framework, Item

HEADER = ("# SYNTHETIC DATA generated by `lamf synth` for demonstration only. "
          "These responses describe no real person or organisation.\n")


@dataclass(frozen=True)
class Persona:
    """A fictional organisation profile."""

    org_id: str
    description: str
    n_respondents: int
    tendencies: dict[str, float]          # dimension id -> latent 1-5 level
    context: dict[str, float]             # context item id -> latent 1-5
    item_shifts: dict[str, float] | None = None  # optional per-item offsets


PERSONAS: tuple[Persona, ...] = (
    Persona("courier-small", "Owner-run urban courier, spreadsheets and phone calls, ~25 staff",
            4, {"maturity": 1.2, "routines": 1.8, "literacy": 2.6, "culture": 2.4, "autonomy": 2.0, "interpretation": 2.2},
            {"q35": 4.2, "q36": 3.6, "q37": 4.5}),
    Persona("3pl-growing", "Growing 3PL that bought a predictive WMS add-on; analytics sits with one person",
            5, {"maturity": 3.3, "routines": 3.0, "literacy": 2.8, "culture": 3.4, "autonomy": 2.9, "interpretation": 2.8},
            {"q35": 4.4, "q36": 4.3, "q37": 4.6}, item_shifts={"q21": -1.4}),
    Persona("fulfilment-hub", "Data-led fulfilment hub piloting AGVs, shared dashboards and defined thresholds",
            6, {"maturity": 3.6, "routines": 4.3, "literacy": 4.1, "culture": 4.2, "autonomy": 3.7, "interpretation": 3.8},
            {"q35": 3.4, "q36": 3.8, "q37": 4.4}),
)


def _answer(item: Item, latent: float, rng: np.random.Generator) -> str:
    """Draw one raw answer for an item given a latent 1-5 tendency."""
    x = float(np.clip(latent + rng.normal(0, 0.6), 1, 5))
    if item.type == "likert":
        v = int(round(x))
        return str(6 - v if item.reverse else v)
    if item.type == "choice":
        return min(item.options.values(), key=lambda o: abs((o.score or 0) - x)).code
    k = int(round((x - 1) / 4 * len(item.options)))  # multi-select: more practices at higher maturity
    if k == 0:
        return "none"
    return ";".join(rng.choice(list(item.options), size=k, replace=False))


def generate(fw: Framework, seed: int = 42, personas: tuple[Persona, ...] = PERSONAS) -> pd.DataFrame:
    """Build a synthetic responses table matching the framework's items."""
    rng = np.random.default_rng(seed)
    rows = []
    for p in personas:
        for r in range(1, p.n_respondents + 1):
            row = {"org_id": p.org_id, "respondent_id": f"{p.org_id}-r{r}"}
            for d in fw.dimensions:
                for item in d.items:
                    latent = p.tendencies[d.id] + (p.item_shifts or {}).get(item.id, 0.0)
                    row[item.id] = _answer(item, latent, rng)
            for item in fw.context_items:
                row[item.id] = _answer(item, p.context.get(item.id, 3.0), rng)
            rows.append(row)
    return pd.DataFrame(rows)


def write_synthetic(fw: Framework, path: str | Path, seed: int = 42) -> Path:
    """Write the synthetic CSV with a comment header labelling it synthetic."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    df = generate(fw, seed)
    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write(HEADER)
        df.to_csv(fh, index=False)
    return path
